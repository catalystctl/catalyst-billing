-- 0038_oauth.sql
--
-- The OAuth2 authorization server (IDN-11) and social login (IDN-07…IDN-10): clients,
-- the authorization-code grant with PKCE, rotating refresh tokens, consent, the generic
-- OIDC provider rows the sign-in screen reads, and the link between a provider subject and
-- an account.
--
-- One migration covers both halves because they are one subject: who a third party is
-- allowed to be, and which account it is allowed to be. Splitting them would have produced
-- two half-tables and a moment where the panel could issue a token for a client it could
-- not describe.
--
-- Five decisions are recorded here, because each one is load-bearing and each one is the
-- kind a later "simplification" quietly undoes:
--
-- 1. **A scope is a permission name, not a second vocabulary.** `allowed_scopes`, the
--    granted scopes and the token's scopes are all `authn.Permission` strings, and they are
--    intersected with the owner's live permissions at issue time *and* at use time (see
--    internal/oauth/scope.go and the `withAPIKey` path in httpapi). A separate scope
--    vocabulary would need its own mapping to permissions, and that mapping is where a
--    token quietly outlives the role that justified it. There is no `scopes` table: the
--    closed set lives in `internal/authn/authz.go`, so a scope this build does not declare
--    cannot be stored at all (the service validates, and a typo fails closed).
--
-- 2. **Every credential is stored as a SHA-256 digest, never as the credential.** The
--    client secret, the authorization code, the access token and the refresh token are 256
--    bits of server randomness, so a digest is the right storage: a database leak is not a
--    credential leak, and there is no endpoint that can reveal a secret a second time. The
--    one-time display in the UI is the create/rotate response and nothing else.
--
-- 3. **The refresh token rotates, and the grant is the family.** `oauth_grants` is one row
--    per authorization and owns the refresh digest; `oauth_access_tokens` are the
--    short-lived children. Exchanging a refresh token replaces the digest on the grant row
--    in the same transaction that issues the new access token, so a replayed refresh token
--    finds a digest that no longer matches and is refused. Revoking the grant
--    (`revoked_at`) kills every token it ever issued, which is what "sign out of the app"
--    has to mean.
--
-- 4. **The state signing key lives in the database, not in an environment variable.** The
--    social-login `state` is signed with HMAC-SHA256 so a callback cannot be driven by a
--    forged state, and single-use because the nonce is consumed by a row. A key in the
--    environment would have to be added to `cmd/billing` and to every deployment's secrets;
--    the row here is generated by this migration from `gen_random_uuid()` (which is a CSPRNG)
--    and can be rotated by updating it, which invalidates outstanding states — exactly the
--    right blast radius for a value that lives for ten minutes.
--
-- 5. **A social login never creates and never merges an account.** `social_identities` is
--    the only place a provider subject is bound to a user, and the binding is created by a
--    *signed-in* user linking their own account (and only when the provider's verified email
--    equals their account email), or it is not created at all. There is deliberately no
--    "find or create user by email" path: an email from an identity provider is an assertion
--    by a third party, and treating it as proof of ownership of a Catalyst account is the
--    account-takeover bug this whole table exists to prevent. A callback whose email matches
--    an existing account is refused with a message telling the person to sign in and link.
--
-- Nothing here touches an issued invoice, a journal entry or an audit row.

BEGIN;

-- =============================================================== oauth clients ==
--
-- A client is a third-party application an operator registered. `client_id` is the public
-- identifier that appears in redirects, so it is constrained to the shape the service
-- generates: a typo in a registered id would send a customer to a URL that does not exist,
-- and that is a support ticket rather than a security problem, but the CHECK makes the
-- canonical form a fact about the data.
--
-- `secret_hash` is NULL exactly when the client is public. A public client cannot keep a
-- secret (it is a browser or a CLI), so it authenticates with PKCE alone; the CHECK keeps
-- the two columns from disagreeing, which would otherwise let a client be created as
-- confidential with no secret and then authenticate as if it had one.

CREATE TABLE oauth_clients (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id       text NOT NULL UNIQUE
        CHECK (client_id ~ '^oc_[0-9a-f]{24}$'),
    name            text NOT NULL
        CHECK (length(name) BETWEEN 1 AND 120),
    -- SHA-256 of the secret. NULL means "public client": no secret exists, so nothing can
    -- be presented and PKCE is the only proof.
    secret_hash     bytea,
    confidential    boolean NOT NULL,
    -- The exact redirect URIs this client may be sent to. Exact match, no prefix match and
    -- no wildcard: a prefix match is how an open redirect becomes a token leak.
    redirect_uris   text[] NOT NULL
        CHECK (cardinality(redirect_uris) BETWEEN 1 AND 10),
    -- The ceiling of what this client may ever ask for. The token is the intersection of
    -- this, the request and the owner's live permissions.
    allowed_scopes  text[] NOT NULL,
    enabled         boolean NOT NULL DEFAULT true,
    created_by      uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    -- When the secret was last rotated, so the screen can show "rotated 3 days ago" instead
    -- of leaving an operator to guess whether the credential in their config is current.
    secret_rotated_at timestamptz,
    CONSTRAINT oauth_clients_secret_matches_kind CHECK (
        (confidential AND secret_hash IS NOT NULL) OR (NOT confidential AND secret_hash IS NULL)
    )
);

-- Deleting a client is a real delete: it revokes nothing retroactively in the audit log, but
-- every dependent row goes with it (codes, grants, tokens, consents) because a token for a
-- client that no longer exists cannot be reasoned about.

-- ================================================================ oauth consent ==
--
-- Consent is remembered per (client, user) with the scopes that were shown. A later
-- authorization that asks for a subset is silent; one that asks for more asks again. The
-- primary key is the pair, so a user has one consent row per client rather than a growing
-- history: the question "what did I agree to" is answered by the current scopes.

CREATE TABLE oauth_consents (
    client_id  uuid NOT NULL REFERENCES oauth_clients (id) ON DELETE CASCADE,
    user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scopes     text[] NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (client_id, user_id)
);

-- ============================================================ oauth auth codes ==
--
-- An authorization code is a bearer credential with a thirty-second life, stored as a
-- digest, consumable exactly once (`consumed_at`). PKCE is recorded with the code, because
-- the exchange has to prove the same client that started the flow is finishing it — the
-- check is at exchange time, against the row, not against a session.
--
-- `code_challenge_method` is constrained to S256: `plain` is permitted by RFC 7636 and is
-- worth nothing against an attacker who can read the code, so this server does not offer it.

CREATE TABLE oauth_auth_codes (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    code_hash             bytea NOT NULL UNIQUE,
    client_id             uuid NOT NULL REFERENCES oauth_clients (id) ON DELETE CASCADE,
    user_id               uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    redirect_uri          text NOT NULL,
    scopes                text[] NOT NULL,
    code_challenge        text
        CHECK (code_challenge IS NULL OR code_challenge ~ '^[A-Za-z0-9_-]{43}$'),
    code_challenge_method text
        CHECK (code_challenge_method IS NULL OR code_challenge_method = 'S256'),
    expires_at            timestamptz NOT NULL,
    consumed_at           timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT oauth_auth_codes_pkce_pair CHECK (
        (code_challenge IS NULL) = (code_challenge_method IS NULL)
    )
);

CREATE INDEX oauth_auth_codes_expiry ON oauth_auth_codes (expires_at);

-- ================================================================ oauth grants ==
--
-- One row per authorization: the family a rotating refresh token belongs to. `refresh_hash`
-- is replaced on every exchange (rotation), so a stolen-and-replayed refresh token is a
-- mismatch rather than a second access token. The grant's `scopes` are the issue-time
-- intersection and are what every child token inherits; they are never widened.

CREATE TABLE oauth_grants (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id    uuid NOT NULL REFERENCES oauth_clients (id) ON DELETE CASCADE,
    user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scopes       text[] NOT NULL,
    -- NULL once the grant has been revoked and its refresh digest cleared, so the digest
    -- column can never be matched after revocation even if it leaked.
    refresh_hash bytea UNIQUE,
    rotated_at   timestamptz,
    expires_at   timestamptz NOT NULL,
    revoked_at   timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX oauth_grants_user ON oauth_grants (user_id);
CREATE INDEX oauth_grants_expiry ON oauth_grants (expires_at);

-- ======================================================== oauth access tokens ==
--
-- The short-lived bearer credential. Its scopes are copied from the grant at issue so that
-- narrowing a grant later does not silently widen a token already handed out, and so the
-- use-time check has something to intersect with.
--
-- `last_used_at` is written at most once a minute (see Authenticate): a read endpoint that
-- writes on every request makes every GET contend on one row.

CREATE TABLE oauth_access_tokens (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    grant_id     uuid NOT NULL REFERENCES oauth_grants (id) ON DELETE CASCADE,
    token_hash   bytea NOT NULL UNIQUE,
    scopes       text[] NOT NULL,
    expires_at   timestamptz NOT NULL,
    revoked_at   timestamptz,
    last_used_at timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX oauth_access_tokens_grant ON oauth_access_tokens (grant_id);
CREATE INDEX oauth_access_tokens_expiry ON oauth_access_tokens (expires_at);

-- ============================================================== social providers ==
--
-- One generic row per OIDC/OAuth2 provider. Google, GitHub and Discord are rows, not three
-- implementations: the differences that matter (endpoints, scopes, which claim carries the
-- subject and which carries the email) are data, and a fourth provider is an insert.
--
-- `client_secret` is stored as text and redacted on every read path (never selected into a
-- response), which is the same contract `settings.is_secret` uses. `email_verified_claim`
-- is optional because Discord and GitHub do not publish one: when it is set, the callback
-- requires the claim to be true before it will bind an email to an account.

CREATE TABLE social_providers (
    id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    slug                   text NOT NULL UNIQUE
        CHECK (slug ~ '^[a-z0-9][a-z0-9_-]{1,31}$'),
    name                   text NOT NULL
        CHECK (length(name) BETWEEN 1 AND 80),
    issuer_url             text NOT NULL,
    authorization_endpoint text NOT NULL,
    token_endpoint         text NOT NULL,
    userinfo_endpoint      text NOT NULL,
    client_id              text NOT NULL,
    client_secret          text NOT NULL,
    scopes                 text[] NOT NULL DEFAULT ARRAY['openid', 'email'],
    subject_claim          text NOT NULL DEFAULT 'sub',
    email_claim            text NOT NULL DEFAULT 'email',
    email_verified_claim   text,
    -- A provider is created disabled: an operator registers it, pastes the credentials the
    -- provider's console gave them, and only then turns it on. A half-configured provider
    -- that is already on the sign-in screen is a broken button.
    enabled                boolean NOT NULL DEFAULT false,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);

-- ========================================================= social login states ==
--
-- The `state` parameter is signed (HMAC-SHA256, key in oauth_signing_keys) *and* single use
-- (this row, consumed once). Signature alone would let a state be replayed within its
-- lifetime; a row alone would let an attacker mint a state by guessing. Both together are
-- what make the callback trustworthy.
--
-- `mode` is what the flow is for: `signin` ends in a session, `link` binds the provider
-- subject to the signed-in user and ends in a redirect to the security screen. `user_id` is
-- set only for `link`, and is what stops a link state from being used to bind somebody
-- else's provider account.

CREATE TABLE social_login_states (
    nonce_hash  bytea PRIMARY KEY,
    provider_id uuid NOT NULL REFERENCES social_providers (id) ON DELETE CASCADE,
    mode        text NOT NULL CHECK (mode IN ('signin', 'link')),
    user_id     uuid REFERENCES users (id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL,
    consumed_at timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT social_login_states_link_needs_user CHECK (
        (mode = 'link') = (user_id IS NOT NULL)
    )
);

-- ============================================================ social identities ==
--
-- The binding between a provider subject and an account. Two unique constraints, and both
-- matter:
--
--   * (provider_id, subject) — one account per provider identity. A second callback for the
--     same subject must resolve to the same user, never create another binding.
--   * (provider_id, user_id) — one identity per provider per account, so a link cannot be
--     used to shadow an existing binding.
--
-- `email` records the address the provider asserted at link time, for the operator's
-- benefit when a customer asks "which account is this". It is not an identity: nothing looks
-- an account up by it.

CREATE TABLE social_identities (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    provider_id uuid NOT NULL REFERENCES social_providers (id) ON DELETE CASCADE,
    user_id     uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    subject     text NOT NULL,
    email       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider_id, subject),
    UNIQUE (provider_id, user_id)
);

CREATE INDEX social_identities_user ON social_identities (user_id);

-- ========================================================= oauth signing keys ==
--
-- The HMAC key for a social-login state. Generated here rather than configured, because a
-- value with a ten-minute useful life does not deserve a deployment secret. Four UUIDs is
-- 64 bytes from the server's CSPRNG; rotating it is an UPDATE, which invalidates states in
-- flight — the correct blast radius.

CREATE TABLE oauth_signing_keys (
    id         text PRIMARY KEY,
    key        bytea NOT NULL CHECK (octet_length(key) >= 32),
    created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO oauth_signing_keys (id, key) VALUES (
    'social-state',
    decode(replace(
        gen_random_uuid()::text || gen_random_uuid()::text ||
        gen_random_uuid()::text || gen_random_uuid()::text, '-', ''), 'hex')
);

COMMIT;
