// Persistence for the update check, the approval and telemetry delivery.
//
// The cache lives in the database rather than in the process because a deployment runs
// `serve` and `worker` as separate processes, and a second instance of `serve` behind a
// proxy is normal. An in-memory cache would let each process fetch the update server
// independently, which is the denial of service this cache exists to prevent.

// ErrNoApproval is returned by Approval when no update has been approved.
var ErrNoApproval = errors.New("updates: no update has been approved")

// Store is the database side of the updates package.
type Store struct {
	pool *store.Pool
	// Now is injectable so a test can age a cache entry without sleeping.
	Now func() time.Time
}

// New constructs a Store.
func New(pool *store.Pool) *Store {
	return &Store{pool: pool, Now: func() time.Time { return time.Now().UTC() }}
}

// Config is the update configuration that is not a settings key.
type Config struct {
	// TelemetryEndpoint is where a payload would be POSTed. It is treated as a credential:
	// it commonly carries an ingest token in the path or query, so it is never returned by
	// a read path. Empty means telemetry cannot be delivered.
	TelemetryEndpoint string
	// InstanceID is this installation's random identifier. It is generated by the
	// database, is unrelated to any customer, and exists only so a receiver can tell two
	// installations apart.
	InstanceID string
	UpdatedAt  time.Time
}

// EndpointHost returns the host of the telemetry endpoint, for display. It deliberately
// drops the path and query, which is where an ingest token usually lives.
func (c Config) EndpointHost() string {
	if c.TelemetryEndpoint == "" {
		return ""
	}
	u, err := url.Parse(c.TelemetryEndpoint)
	if err != nil || u.Host == "" {
		return ""
	}
	return u.Host
}

// Config reads the singleton row, creating it when it is absent.
//
// "A missing row is a default, not an error" is the rule `internal/settings` already applies
// to every setting, and the same reasoning holds here: the configuration row is a default an
// operator edits, so a fresh installation, or a database whose rows a test truncated, must
// read as the defaults rather than as a broken installation. The instance id is generated by
// the database on that insert and then stable forever, which is what makes it an identifier
// rather than a nonce.
func (s *Store) Config(ctx context.Context) (Config, error) {
	if _, err := s.pool.Exec(ctx,
		`INSERT INTO update_config (id) VALUES (true) ON CONFLICT (id) DO NOTHING`); err != nil {
		return Config{}, fmt.Errorf("updates: ensure config: %w", err)
	}
	var out Config
	err := s.pool.QueryRow(ctx, `
		SELECT telemetry_endpoint, instance_id::text, updated_at FROM update_config WHERE id`).
		Scan(&out.TelemetryEndpoint, &out.InstanceID, &out.UpdatedAt)
	if err != nil {
		return Config{}, fmt.Errorf("updates: read config: %w", err)
	}
	out.UpdatedAt = out.UpdatedAt.UTC()
	return out, nil
}

// SetTelemetryEndpoint writes the endpoint inside a caller's transaction.
//
// It takes a transaction rather than opening its own because the audit row for the change
// must be committed with it: a rolled-back configuration change must not leave an audit row
// claiming it happened.
func (s *Store) SetTelemetryEndpoint(ctx context.Context, tx pgx.Tx, endpoint, actorID string) error {
	_, err := tx.Exec(ctx, `
		INSERT INTO update_config (id, telemetry_endpoint, updated_at, updated_by)
		VALUES (true, $1, now(), $2)
		ON CONFLICT (id) DO UPDATE
			SET telemetry_endpoint = EXCLUDED.telemetry_endpoint,
			    updated_at = now(),
			    updated_by = EXCLUDED.updated_by`,
		strings.TrimSpace(endpoint), nullableUUID(actorID))
	if err != nil {
		return fmt.Errorf("updates: write config: %w", err)
	}
	return nil
}

// Approval is the version an operator approved, and who approved it.
type Approval struct {
	Version    string    `json:"version"`
	Note       string    `json:"note"`
	ApprovedBy string    `json:"approved_by"`
	ApprovedAt time.Time `json:"approved_at"`
}

// Approval reads the current approval.
func (s *Store) Approval(ctx context.Context) (*Approval, error) {
	var out Approval
	var approvedBy *string
	err := s.pool.QueryRow(ctx, `
		SELECT version, note, approved_by::text, approved_at
		FROM update_approval WHERE id`).Scan(&out.Version, &out.Note, &approvedBy, &out.ApprovedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrNoApproval
	}
	if err != nil {
		return nil, fmt.Errorf("updates: read approval: %w", err)
	}
	if approvedBy != nil {
		out.ApprovedBy = *approvedBy
	}
	out.ApprovedAt = out.ApprovedAt.UTC()
	return &out, nil
}

// SetApproval records an approved version inside a caller's transaction.
//
// One row, replaced: an approval supersedes the previous one, and the audit log is where
// the history lives. Keeping a history table here would duplicate the audit log with fewer
// guarantees.
func (s *Store) SetApproval(ctx context.Context, tx pgx.Tx, version, note, actorID string) error {
	_, err := tx.Exec(ctx, `
		INSERT INTO update_approval (id, version, note, approved_by, approved_at)
		VALUES (true, $1, $2, $3, now())
		ON CONFLICT (id) DO UPDATE
			SET version = EXCLUDED.version,
			    note = EXCLUDED.note,
			    approved_by = EXCLUDED.approved_by,
			    approved_at = EXCLUDED.approved_at`,
		strings.TrimSpace(version), strings.TrimSpace(note), nullableUUID(actorID))
	if err != nil {
		return fmt.Errorf("updates: write approval: %w", err)
	}
	return nil
}

// ClearApproval removes the approval inside a caller's transaction.
func (s *Store) ClearApproval(ctx context.Context, tx pgx.Tx) error {
	if _, err := tx.Exec(ctx, `DELETE FROM update_approval WHERE id`); err != nil {
		return fmt.Errorf("updates: clear approval: %w", err)
	}
	return nil
}

// Cached returns the stored check, if it is still about the same URL, channel and running
// version.
//
// A cache entry that was written by a different build is discarded rather than reused: "1.5.0
// available" is only an answer relative to the version that asked, and after an in-place
// upgrade the old answer would be a lie that also suppresses the new check.
func (s *Store) Cached(ctx context.Context, sourceURL, channel, running string) (*Result, bool, error) {
	var (
		out         Result
		publishedAt *time.Time
	)
	err := s.pool.QueryRow(ctx, `
		SELECT source_url, channel, running_version, latest_version, download_url, notes,
		       published_at, checked_at, failure_code
		FROM update_check WHERE id`).
		Scan(&out.SourceURL, &out.Channel, &out.RunningVersion, &out.LatestVersion,
			&out.DownloadURL, &out.Notes, &publishedAt, &out.CheckedAt, &out.FailureCode)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, fmt.Errorf("updates: read check: %w", err)
	}
	if out.SourceURL != sourceURL || out.Channel != channel || out.RunningVersion != running {
		return nil, false, nil
	}

	out.Configured = true
	out.PublishedAt = utcPtr(publishedAt)
	out.CheckedAt = out.CheckedAt.UTC()
	out.Cached = true
	expires := out.CheckedAt.Add(out.CacheTTL())
	out.ExpiresAt = &expires

	if out.FailureCode != "" {
		out.Outcome = OutcomeUnreachable
		out.Detail = "the last update check failed"
	} else {
		// Recompute the outcome from the stored versions instead of storing it: the
		// comparison is cheap, and a stored outcome could disagree with the versions it
		// was derived from after a hand-edited row.
		out.Outcome = compareOutcome(running, out.LatestVersion)
	}
	return &out, true, nil
}

// Save stores a check result, replacing the singleton.
func (s *Store) Save(ctx context.Context, r Result) error {
	_, err := s.pool.Exec(ctx, `
		INSERT INTO update_check (id, source_url, channel, running_version, latest_version,
		                          download_url, notes, published_at, checked_at, failure_code)
		VALUES (true, $1, $2, $3, $4, $5, $6, $7, $8, $9)
		ON CONFLICT (id) DO UPDATE
			SET source_url = EXCLUDED.source_url,
			    channel = EXCLUDED.channel,
			    running_version = EXCLUDED.running_version,
			    latest_version = EXCLUDED.latest_version,
			    download_url = EXCLUDED.download_url,
			    notes = EXCLUDED.notes,
			    published_at = EXCLUDED.published_at,
			    checked_at = EXCLUDED.checked_at,
			    failure_code = EXCLUDED.failure_code`,
		r.SourceURL, r.Channel, r.RunningVersion, r.LatestVersion, r.DownloadURL, r.Notes,
		r.PublishedAt, r.CheckedAt, r.FailureCode)
	if err != nil {
		return fmt.Errorf("updates: write check: %w", err)
	}
	return nil
}

// Check answers "is there a newer version", using the cache unless force is set.
//
// This is the whole policy in one place, which is what makes it testable: a fresh cached
// answer is returned as-is; `force` fetches; a failed fetch is cached with the shorter
// failure TTL and returned as an unreachable outcome rather than an error, because a broken
// update server must not make the settings page fail to load.
func (s *Store) Check(ctx context.Context, running, channel, sourceURL string, force bool, fetcher *Fetcher) (Result, error) {
	now := s.Now()
	sourceURL = strings.TrimSpace(sourceURL)
	if sourceURL == "" {
		return NotConfiguredResult(running, channel), nil
	}

	if !force {
		cached, ok, err := s.Cached(ctx, sourceURL, channel, running)
		if err != nil {
			return Result{}, err
		}
		if ok && cached.Fresh(now) {
			return *cached, nil
		}
	}

	if fetcher == nil {
		fetcher = NewFetcher()
	}
	manifest, err := fetcher.Fetch(ctx, sourceURL)
	if err != nil {
		code, message := asCheckError(err)
		result := FailureResult(running, channel, sourceURL, code, message, now)
		expires := now.Add(result.CacheTTL())
		result.ExpiresAt = &expires
		// A failure is cached, and a failure to write the cache must not hide the failure
		// that caused it: the caller still gets the real answer.
		if saveErr := s.Save(ctx, result); saveErr != nil {
			return result, saveErr
		}
		return result, nil
	}

	result := BuildResult(running, channel, sourceURL, manifest, now)
	expires := now.Add(result.CacheTTL())
	result.ExpiresAt = &expires
	if err := s.Save(ctx, result); err != nil {
		return Result{}, err
	}
	return result, nil
}

// compareOutcome re-derives the outcome from two version strings.
func compareOutcome(running, latest string) Outcome {
	runningVersion, runErr := ParseVersion(running)
	latestVersion, latestErr := ParseVersion(latest)
	if runErr != nil || latestErr != nil {
		return OutcomeUnknown
	}
	switch runningVersion.Compare(latestVersion) {
	case 0:
		return OutcomeUpToDate
	case -1:
		return OutcomeAvailable
	default:
		return OutcomeAhead
	}
}

// utcPtr converts a nullable timestamp to a UTC pointer.
func utcPtr(t *time.Time) *time.Time {
	if t == nil {
		return nil
	}
	out := t.UTC()
	return &out
}

// nullableUUID renders an empty actor id as SQL NULL, because the columns are uuid
// references and "" is not a uuid.
func nullableUUID(s string) any {
	if strings.TrimSpace(s) == "" {
		return nil
	}
	return s
}
