// Telemetry.
//
// It is off unless an operator turns it on (`updates.telemetry`, which defaults to false),
// and when it is on the payload is a *fixed* document: counts, versions and nothing else.
// There is no free-form field, no map, no "extras", and no column anywhere in the schema
// that could contribute one. That is the design, not a policy statement: a payload assembled
// from a struct with seven integers and six short strings cannot grow a customer by
// accident, and the test in telemetry_test.go asserts the exact key set and greps the encoded
// bytes for a seeded customer's address and name.
//
// What is deliberately absent:
//
//   - no customer identifiers, names or addresses;
//   - no invoice, order or payment contents (only how many are open);
//   - no hostname, domain, IP address or public URL;
//   - no operator identity, no API keys, no gateway credentials;
//   - no extension names (which can be a business detail), only how many are installed.
//
// The one identifier is `instance_id`: a random UUID generated by the database when the
// installation was migrated. It is not derived from anything, it identifies the installation
// rather than a person, and it is shown in the preview so an operator can see it.

// PayloadSchemaVersion is the version of the telemetry document itself. A receiver that does
// not know this version must ignore the payload rather than guess at its fields.
const PayloadSchemaVersion = 1

// TelemetryTimeout bounds a delivery. A telemetry receiver that never answers must not hold
// a request open.
const TelemetryTimeout = 10 * time.Second

// MaxTelemetryResponseBytes bounds how much of the receiver's answer is read. It is discarded;
// the bound exists so a hostile or broken endpoint cannot stream forever.
const MaxTelemetryResponseBytes = 4 << 10

// Counts is the fixed set of totals a payload carries.
//
// Every field is an integer. There is no key that could hold a string, which is what makes
// "nothing identifying" a property of the type rather than a promise.
type Counts struct {
	Customers           int `json:"customers"`
	ServicesActive      int `json:"services_active"`
	ServicesSuspended   int `json:"services_suspended"`
	InvoicesOpen        int `json:"invoices_open"`
	InvoicesPaidLast30d int `json:"invoices_paid_last_30d"`
	TicketsOpen         int `json:"tickets_open"`
	ExtensionsInstalled int `json:"extensions_installed"`
}

// Payload is the whole telemetry document.
//
// The JSON key set is asserted by a test, so adding a field is a deliberate act with a
// failing test to review rather than an accident.
type Payload struct {
	SchemaVersion int    `json:"schema_version"`
	InstanceID    string `json:"instance_id"`
	PanelVersion  string `json:"panel_version"`
	Channel       string `json:"channel"`
	GoVersion     string `json:"go_version"`
	OS            string `json:"os"`
	Arch          string `json:"arch"`
	// DatabaseSchemaVersion is the highest applied migration version. It answers "which
	// schema is this installation on", which is the first question a support engineer asks.
	// It is a number, not a migration file name.
	DatabaseSchemaVersion int       `json:"database_schema_version"`
	GeneratedAt           time.Time `json:"generated_at"`
	Counts                Counts    `json:"counts"`
}

// BuildPayload assembles the telemetry document.
//
// It returns (nil, nil) when telemetry is disabled: "empty when off" is enforced here rather
// than in a handler, so a future caller cannot build a payload for a disabled installation by
// forgetting a branch.
func (s *Store) BuildPayload(ctx context.Context, runningVersion, channel string, enabled bool) (*Payload, error) {
	if !enabled {
		return nil, nil
	}
	cfg, err := s.Config(ctx)
	if err != nil {
		return nil, err
	}
	counts, err := s.counts(ctx)
	if err != nil {
		return nil, err
	}
	schemaVersion, err := s.databaseSchemaVersion(ctx)
	if err != nil {
		return nil, err
	}
	return &Payload{
		SchemaVersion:         PayloadSchemaVersion,
		InstanceID:            cfg.InstanceID,
		PanelVersion:          runningVersion,
		Channel:               channel,
		GoVersion:             runtime.Version(),
		OS:                    runtime.GOOS,
		Arch:                  runtime.GOARCH,
		DatabaseSchemaVersion: schemaVersion,
		GeneratedAt:           s.Now().UTC(),
		Counts:                counts,
	}, nil
}

// counts reads every total in one statement, so the payload is a single snapshot rather than
// seven reads that can disagree with each other.
func (s *Store) counts(ctx context.Context) (Counts, error) {
	var out Counts
	err := s.pool.QueryRow(ctx, `
		SELECT
		    (SELECT count(*) FROM customers),
		    (SELECT count(*) FROM services WHERE status = 'active'),
		    (SELECT count(*) FROM services WHERE status = 'suspended'),
		    (SELECT count(*) FROM invoices WHERE status = 'open'),
		    (SELECT count(*) FROM invoices
		      WHERE status = 'paid' AND issued_at > now() - interval '30 days'),
		    (SELECT count(*) FROM tickets WHERE status <> 'closed'),
		    (SELECT count(*) FROM installed_extensions)`).
		Scan(&out.Customers, &out.ServicesActive, &out.ServicesSuspended, &out.InvoicesOpen,
			&out.InvoicesPaidLast30d, &out.TicketsOpen, &out.ExtensionsInstalled)
	if err != nil {
		return Counts{}, fmt.Errorf("updates: read telemetry counts: %w", err)
	}
	return out, nil
}

// databaseSchemaVersion returns the highest applied migration version.
func (s *Store) databaseSchemaVersion(ctx context.Context) (int, error) {
	var version int
	if err := s.pool.QueryRow(ctx,
		`SELECT COALESCE(max(version), 0) FROM schema_migrations`).Scan(&version); err != nil {
		return 0, fmt.Errorf("updates: read schema version: %w", err)
	}
	return version, nil
}

// EncodePayload renders a payload to its exact wire bytes.
//
// The bytes are what gets hashed and recorded, so the record of "what we sent" is the thing
// that was sent rather than a re-rendering of it.
func EncodePayload(p Payload) ([]byte, error) {
	body, err := json.Marshal(p)
	if err != nil {
		return nil, fmt.Errorf("updates: encode telemetry payload: %w", err)
	}
	return body, nil
}

// SendResult is the outcome of one delivery attempt.
type SendResult struct {
	ID           string    `json:"id"`
	SentAt       time.Time `json:"sent_at"`
	Status       string    `json:"status"`
	HTTPStatus   int       `json:"http_status"`
	FailureCode  string    `json:"failure_code"`
	PayloadSHA   string    `json:"payload_sha256"`
	EndpointHost string    `json:"endpoint_host"`
}

// Send records and delivers a payload.
//
// The attempt is recorded whether or not it succeeded, so a delivery that timed out is
// visible instead of vanishing. The request is bounded in both directions: a receiver that
// never answers cannot hold the request open, and one that answers with a gigabyte is not
// read.
func (s *Store) Send(ctx context.Context, endpoint string, payload Payload, actorID string, client *http.Client) (SendResult, error) {
	body, err := EncodePayload(payload)
	if err != nil {
		return SendResult{}, err
	}
	sum := sha256.Sum256(body)
	digest := hex.EncodeToString(sum[:])

	result := SendResult{
		Status:       "failed",
		PayloadSHA:   digest,
		EndpointHost: Config{TelemetryEndpoint: endpoint}.EndpointHost(),
	}

	if client == nil {
		client = &http.Client{Timeout: TelemetryTimeout}
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		result.FailureCode = "telemetry_endpoint_invalid"
	} else {
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("User-Agent", "catalyst-billing/"+payload.PanelVersion)
		resp, doErr := client.Do(req)
		switch {
		case doErr != nil:
			result.FailureCode = "telemetry_delivery_failed"
		default:
			_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, MaxTelemetryResponseBytes))
			_ = resp.Body.Close()
			result.HTTPStatus = resp.StatusCode
			if resp.StatusCode >= 200 && resp.StatusCode < 300 {
				result.Status = "sent"
			} else {
				result.FailureCode = "telemetry_rejected"
			}
		}
	}

	if err := s.pool.QueryRow(ctx, `
		INSERT INTO telemetry_sends (endpoint_host, payload, payload_sha256, status,
		                             http_status, failure_code, sent_by)
		VALUES ($1, $2::jsonb, $3, $4, $5, $6, $7)
		RETURNING id::text, sent_at`,
		result.EndpointHost, string(body), digest, result.Status, result.HTTPStatus,
		result.FailureCode, nullableUUID(actorID)).Scan(&result.ID, &result.SentAt); err != nil {
		return result, fmt.Errorf("updates: record telemetry send: %w", err)
	}
	result.SentAt = result.SentAt.UTC()
	return result, nil
}

// LastSend is the most recent recorded delivery, for the state endpoint.
type LastSend struct {
	ID           string    `json:"id"`
	SentAt       time.Time `json:"sent_at"`
	Status       string    `json:"status"`
	HTTPStatus   int       `json:"http_status"`
	FailureCode  string    `json:"failure_code"`
	EndpointHost string    `json:"endpoint_host"`
}

// LastTelemetrySend returns the most recent delivery, or nil when none has been attempted.
func (s *Store) LastTelemetrySend(ctx context.Context) (*LastSend, error) {
	var out LastSend
	err := s.pool.QueryRow(ctx, `
		SELECT id::text, sent_at, status, http_status, failure_code, endpoint_host
		FROM telemetry_sends ORDER BY sent_at DESC LIMIT 1`).
		Scan(&out.ID, &out.SentAt, &out.Status, &out.HTTPStatus, &out.FailureCode, &out.EndpointHost)
	if err != nil {
		if errorsIsNoRows(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("updates: read last telemetry send: %w", err)
	}
	out.SentAt = out.SentAt.UTC()
	return &out, nil
}

// errorsIsNoRows reports whether err is pgx's "no rows".
func errorsIsNoRows(err error) bool {
	return err == pgx.ErrNoRows
}
